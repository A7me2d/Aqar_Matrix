  // «مشارك مجهول الهوية» = ناس مختلفة، مينفعش يتجمعوا في شخص واحد
  const ANON_RE = /(مشارك مجهول|عضو مجهول|مجهول الهويه|anonymous participant|anonymous member|group member)/i;
