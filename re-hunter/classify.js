  function say(text, opts) {
    const key = (opts && opts.c ? "c" : "p") + String(text || "");
    let r = SAY_CACHE.get(key);
    if (r) return r;
    r = { owner: null, buyer: null, client: null, broker: null };
    const n = norm(text || "");
    if (n) {
      for (const cl of sayClauses(n)) {
        const t = cl.t;
        if (!t || cl.q) continue; // سؤال = مش تصريح
        const seek = SEEK_V.test(t);
        // ---- مالك ----
        if (!r.owner) {
          for (const [ph, re] of SAY_OWNER) if (re.test(t)) { r.owner = ph; break; }
          if (!r.owner && !seek) {
            const m = OWN_FROM.exec(t);
            if (m) {
              const idx = m.index + (m[0].startsWith("من") ? 0 : 1);
              const bad = OWN_FROM_BAD.test(lookTok(t, idx, 3) + " ");
              const alone = t.split(" ").length <= 2 && opts && opts.c; // «من المالك» لوحدها في تعليق = غالبًا سؤال
              if (!bad && !alone) r.owner = "من المالك";
            }
          }
        }
        // ---- مشتري ----
        if (!r.buyer && !BUY_NEG.test(t)) {
          for (const [ph, re, bad] of SAY_BUY) {
            const m = re.exec(t);
            if (!m) continue;
            if (bad && bad.test(lookTok(t, m.index, 1) + " ")) continue;
            if (ph === "تفاصيل للشراء" && SELLER_CTX.test(t)) continue;
            if (ph === "مطلوب للشراء" && /(?:^|\s)(?:لعميل|لعميلي|لزبون)(?:\s|$)/.test(t)) continue;
            r.buyer = ph; break;
          }
          if (!r.buyer && BUY_ALONE.test(t) && t.split(" ").length <= 8 && !BUY_ALONE_BAD.test(t)) r.buyer = "للشراء";
        }
        // ---- وسيط عنده عميل ----
        if (!r.client) {
          for (const re of SAY_CLIENT) {
            const m = re.exec(t);
            if (m) { r.client = m[0].trim(); break; }
          }
        }
        // ---- سمسار / مكتب / وسيط بيعرّف نفسه ----
        if (!r.broker) {
          for (const [kind, re] of SAY_BROKER) {
            const m = re.exec(t);
            if (m) { r.broker = { kind, phrase: m[0].replace(/^[^ء-يa-z]+/, "").trim() }; break; }
          }
          if (!r.broker) {
            const m = BROKER_COMM.exec(t);
            if (m && !SAY_NOCOMM.test(t) && !new RegExp(`${NOBROK}$`).test(t.slice(0, m.index + (m[0].startsWith(" ") ? 1 : 0)))) r.broker = { kind: "broker", phrase: m[0].replace(/^[^ء-يa-z]+/, "").trim() };
          }
        }
      }
    }
    if (r.buyer && r.owner === "من المالك") r.owner = null; // «انا مشتري من المالك» = مشتري
    if (SAY_CACHE.size > 6000) SAY_CACHE.clear();
    SAY_CACHE.set(key, r);
    return r;
  }

